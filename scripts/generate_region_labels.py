"""Bake opaque white text + black outlines; the game applies opacity ONCE.

Run with Pillow and the engine's MiSans-Regular.ttf path as the first argument.
The transparent atlas covers every direction/title combination in OriginRegions.
"""
from pathlib import Path
import sys
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
font = ImageFont.truetype(sys.argv[1], 96)
names = [direction + title
         for direction in ('西北', '北', '东北', '西', '中部', '东', '西南', '南', '东南')
         for title in ('丰禾乡', '百工镇', '万家聚', '疏居地')]
atlas = Image.new('RGBA', (488, 108 * len(names)))
draw = ImageDraw.Draw(atlas)
rows = []
for i, name in enumerate(names):
    width = len(name) * 96 + 8
    y = i * 108
    left, top, right, bottom = draw.textbbox((0, 0), name, font=font, stroke_width=2)
    draw.text(((width - right - left) / 2, y + (108 - bottom - top) / 2),
              name, font=font, fill='white', stroke_width=2, stroke_fill='black')
    rows.append(f'    ["{name}"] = {{ y = {y / 2:g}, w = {width / 2:g} }},')
target = root / 'assets' / 'Textures' / 'region-labels.png'
target.parent.mkdir(parents=True, exist_ok=True)
atlas.save(target)
(root / 'scripts' / 'OriginRegionLabelAtlas.lua').write_text(
    '-- Generated by generate_region_labels.py. Coordinates are logical pixels.\n'
    + 'return { width = 244, height = 1944, labels = {\n'
    + '\n'.join(rows) + '\n} }\n', encoding='utf-8')
print(f'Generated {len(names)} labels: {target}')
